#nullable disable warnings
using System;
using System.Collections.Generic;
using System.ComponentModel.Design;
using System.Linq;
using System.Reflection.Metadata.Ecma335;
using System.Text;
using System.Threading.Tasks;
using static NewDawn.Models.Unit;

namespace NewDawn.Models
{
    public class Player
    {
        /// <summary>
        /// Represents a player in the game.
        /// Responsibilities:
        /// - Tracks player resources (Alloy, Fuel) and per-turn income
        /// - Tracks owned/deployed units and buildings
        /// - Validates deployment/placement rules (CMP/Hub proximity, tile availability, affordability)
        /// - Provides helper methods for game loop (GenerateIncome, RefreshUnits, HasLost, etc.)
        /// </summary>
        // ============================================================
        // FIELDS
        // ============================================================
        /// <summary>
        /// Hard cap for resources so values do not grow unbounded or overflow UI/logic.
        /// </summary>
        private const int _maxResources = 9999;

        /// <summary>
        /// Income generated by owned buildings in the current turn.
        /// Computed by UpdateBuildingIncome().
        /// </summary>
        private int _buildingAlloyIncome;
        private int _buildingFuelIncome;

        /// <summary>
        /// Current player resource pools.
        /// These are the "wallet" values.
        /// </summary>
        private int _fuelResources;
        private int _alloyResources;

        /// <summary>
        /// Baseline income per turn not related to buildings.
        /// Buildings add on top via _buildingAlloyIncome/_buildingFuelIncome.
        /// </summary>
        private int _resourcesPerTurnAlloy;
        private int _resourcesPerTurnFuel;

        /// <summary>
        /// Units already deployed on the map (in play).
        /// </summary>
        private List<Unit> _deployedUnits;

        /// <summary>
        /// Units owned by the player but not yet deployed (hand / reserve).
        /// </summary>
        private List<Unit> _availableUnitsToPlace;

        /// <summary>
        /// List of valid targets for attacks, typically computed by Game each turn
        /// and assigned to the player.
        /// </summary>
        private List<Unit> _availableTargets = new List<Unit>();

        /// <summary>
        /// Buildings currently controlled/owned by the player (already placed on map).
        /// </summary>
        private List<Building> _ownedBuildings;

        /// <summary>
        /// Buildings owned but not yet placed (hand / reserve).
        /// </summary>
        private List<Building> _availableBuildingsToPlace;

        // ============================================================
        // PROPERTIES
        // ============================================================
        /// <summary>
        /// Current Alloy resource amount (clamped to [0.._maxResources]).
        /// </summary>
        public int AlloyResources
        {
            get { return _alloyResources; }
            set
            {
                // Clamp into [0.._maxResources]
                if (value >= 0 && value <= _maxResources)
                    _alloyResources = value;
                else if (value > _maxResources)
                    _alloyResources = _maxResources;
                else
                    _alloyResources = 0;
            }
        }

        /// <summary>
        /// Current Fuel resource amount (clamped to [0.._maxResources]).
        /// </summary>
        public int FuelResources
        {
            get { return _fuelResources; }
            set
            {
                // Clamp into [0.._maxResources]
                if (value >= 0 && value <= _maxResources)
                    _fuelResources = value;
                else if (value > _maxResources)
                    _fuelResources = _maxResources;
                else
                    _fuelResources = 0;
            }
        }

        /// <summary>
        /// Base Alloy income per turn (not including building income).
        /// Must be >= 0.
        /// </summary>
        public int ResourcesPerTurnAlloy
        {
            get { return _resourcesPerTurnAlloy; }
            set
            {
                if (value >= 0)
                    _resourcesPerTurnAlloy = value;
                else
                    _resourcesPerTurnAlloy = 0;
            }
        }

        /// <summary>
        /// Base Fuel income per turn (not including building income).
        /// Must be >= 0.
        /// </summary>
        public int ResourcesPerTurnFuel
        {
            get { return _resourcesPerTurnFuel; }
            set
            {
                if (value < 0)
                    _resourcesPerTurnFuel = 0;
                else
                    _resourcesPerTurnFuel = value;
            }
        }

        /// <summary>
        /// Units currently deployed (in play).
        /// Returned as a reference to the internal list.
        /// If you want stricter encapsulation later, expose IReadOnlyList<Unit>.
        /// </summary>
        public List<Unit> DeployedUnits
        {
            get { return _deployedUnits; }
        }

        /// <summary>
        /// Units owned but not deployed.
        /// Returned as a reference to the internal list.
        /// </summary>
        public List<Unit> AvailableUnitsToPlace
        {
            get { return _availableUnitsToPlace; }
        }

        /// <summary>
        /// Buildings owned and controlled by the player (placed on the map).
        /// </summary>
        public List<Building> OwnedBuildings
        {
            get { return _ownedBuildings; }
        }

        /// <summary>
        /// Buildings owned but not placed.
        /// </summary>
        public List<Building> AvailableBuildingsToPlace
        {
            get { return _availableBuildingsToPlace; }
        }

        /// <summary>
        /// Targets the player is currently allowed/able to attack.
        /// Typically computed by Game and injected into the player each turn.
        /// </summary>
        public List<Unit> AvailableTargets
        {
            get { return _availableTargets; }
            set { _availableTargets = value; }
        }

        // ============================================================
        // CONSTRUCTOR
        // ============================================================

        /// <summary>
        /// Creates a player with starting resources.
        /// Defaults:
        /// - startingAlloy = 30 (enough for cheapest units or 2 extractors)
        /// - startingFuel = 0 (forces scouting/building fuel extractors for tactical pacing)
        /// Also initializes internal lists and default base income per turn.
        /// </summary>
        public Player(int startingAlloy = 30, int startingFuel = 0) // should be 0 for fuel, as you have to scout and make fuel extractors to get fuel, to make game slower in a way and more tactical | 30 is default starting alloy for there cheapest units ore two extractors 
        {
            _fuelResources = startingFuel;
            _alloyResources = startingAlloy;

            // Base income per turn (before buildings).
            _resourcesPerTurnAlloy = 5;
            _resourcesPerTurnFuel = 0;

            // Initialize collection state.
            _deployedUnits = new List<Unit>();
            _availableUnitsToPlace = new List<Unit>();
            _ownedBuildings = new List<Building>();
            _availableBuildingsToPlace = new List<Building>();

        }
        // ============================================================
        // RESOURCE MANAGEMENT
        // ============================================================
        /// <summary>
        /// Adds Alloy to the player's pool (ignored if amount <= 0).
        /// Uses AlloyResources setter which clamps to max resources.
        /// </summary>
        public void AddAlloyResources(int amount)
        {
            if (amount > 0)
            {
                AlloyResources += amount;
            }
        }
        /// <summary>
        /// Adds Fuel to the player's pool (ignored if amount <= 0).
        /// Uses FuelResources setter which clamps to max resources.
        /// </summary>
        public void AddFuelResources(int amount)
        {
            if (amount > 0)
            {
                FuelResources += amount;
            }
        }


        /// <summary>
        /// Attempts to spend Alloy.
        /// Returns true if the player had enough and the spend succeeded.
        /// </summary>
        public bool SpendAlloyResources(int amount)
        {
            if (amount > 0 && amount <= AlloyResources)
            {
                AlloyResources -= amount;
                return true;
            }
            return false;
        }
        /// <summary>
        /// Attempts to spend Fuel.
        /// Returns true if the player had enough and the spend succeeded.
        /// </summary>
        public bool SpendFuelResources(int amount)
        {
            if (amount > 0 && amount <= FuelResources)
            {
                FuelResources -= amount;
                return true;
            }
            return false;
        }
        // ============================================================
        // INCOME / ECONOMY
        // ============================================================
        /// <summary>
        /// Generates resources for one turn.
        /// Steps:
        /// 1) UpdateBuildingIncome() recalculates _buildingAlloyIncome/_buildingFuelIncome
        /// 2) Add base per-turn income + building income into the resource pools
        /// </summary>
        public void GenerateIncome()
        {
            UpdateBuildingIncome();

            AddAlloyResources(ResourcesPerTurnAlloy + _buildingAlloyIncome);
            AddFuelResources(ResourcesPerTurnFuel + _buildingFuelIncome);
        }
        /// <summary>
        /// Recalculates building-derived income.
        /// Logic:
        /// - Sum base production from AlloyQuarry and FuelExtractor buildings
        /// - Count multiplicator buildings (AlloyMultiplicator / FuelMultiplicator)
        /// - Apply multipliers by doubling income for each multiplicator
        /// - Apply CMP passive bonus (+1 fuel, +10 alloy) if a CMP is deployed
        /// </summary>
        public void UpdateBuildingIncome() // calculates income from different types of buildings
        {
            int alloyBase = 0;
            int fuelBase = 0;

            int alloyMultipliers = 0;
            int fuelMultipliers = 0;

            foreach (Building b in OwnedBuildings)
            {
                if (b == null) continue;

                switch (b.ThisBuildingType)
                {
                    case Building.BuildingType.AlloyQuarry:
                        alloyBase += b.BuildingyProduction;
                        break;

                    case Building.BuildingType.FuelExtractor:
                        fuelBase += b.BuildingyProduction;
                        break;

                    case Building.BuildingType.AlloyMultiplicator:
                        alloyMultipliers++;
                        break;

                    case Building.BuildingType.FuelMultiplicator:
                        fuelMultipliers++;
                        break;

                    default:
                        break;
                }
            }

            // Apply multipliers by repeated doubling:
            // final = base * 2^(multiplierCount)
            _buildingAlloyIncome = alloyBase;
            for (int i = 0; i < alloyMultipliers; i++)
                _buildingAlloyIncome *= 2;

            _buildingFuelIncome = fuelBase;
            for (int i = 0; i < fuelMultipliers; i++)
                _buildingFuelIncome *= 2;

            // Commander passive income bonus if a CMP is currently deployed.
            if (HasDeployedUnitOfType(UnitType.CMP))
            {
                _buildingFuelIncome += 1;
                _buildingAlloyIncome += 10;
            }
        }
        /// <summary>
        /// Returns true if the player has at least one deployed unit of a given UnitType.
        /// Used for rules/passives like CMP income bonus and deployment anchor checks.
        /// </summary>
        public bool HasDeployedUnitOfType(Unit.UnitType type)
        {
            foreach (Unit u in _deployedUnits)
            {
                if (u == null) continue;
                if (u.ThisUnitType == type)
                    return true;
            }
            return false;
        }

        // ============================================================
        // PURCHASE / DEPLOYMENT (UNITS)
        // ============================================================

        /// <summary>
        /// Returns true if player has enough Alloy to pay a given cost.
        /// </summary>

        public bool CanAfford(int alloyCost)
        {
            return (AlloyResources >= alloyCost);
        }

        /// <summary>
        /// Purchases a MapObject (Unit or Building) by spending its Alloy price.
        /// 
        /// IMPORTANT:
        /// This method only spends resources; it does NOT add the unit/building to any list.
        /// Also, it does not return success/failure:
        /// - If you cannot afford, it silently does nothing.
        /// </summary>
        public void PurchaseUnit(MapObject unitOrBuilding)
        {
            if (CanAfford(unitOrBuilding.PriceAlloy))
            {
                SpendAlloyResources(unitOrBuilding.PriceAlloy);
            }

        }
        /// <summary>
        /// Deploys a unit from AvailableUnitsToPlace onto a map tile.
        /// 
        /// Validation steps:
        /// 1) unit/tile/map must be non-null
        /// 2) unit must be in AvailableUnitsToPlace (player owns it and hasn't deployed it yet)
        /// 3) tile must be empty and walkable
        /// 4) If unit is not a CMP:
        ///    - must be placed within distance 1 of a deployed CMP OR within distance 1 of a Hub building
        /// 5) Spend Alloy cost (only after all placement rules pass)
        /// 6) Move unit from available -> deployed
        /// </summary>
        public bool DeployUnit(Unit unit, Tile tile, Map map)
        {
            if (unit == null || tile == null || map == null)
                return false;

            // Unit must exist in the player's undeployed pool.
            if (!AvailableUnitsToPlace.Contains(unit))
                return false;

            // Tile must be usable (empty & walkable).
            if (tile.IsOccupied() || !tile.IsWalkable())
                return false;

            // CMP has special deployment rule:
            // CMP can be deployed freely (does not require being near another CMP/Hub).
            if (unit.ThisUnitType != Unit.UnitType.CMP)
            {
                // Non-CMP units must deploy within radius 1 of a CMP or Hub.
                bool inRange = false;

                // Check proximity to any deployed CMP.
                foreach (Unit anchorUnit in DeployedUnits)
                {
                    if (anchorUnit == null || anchorUnit.Position == null)
                        continue;

                    if (anchorUnit.ThisUnitType != Unit.UnitType.CMP)
                        continue;

                    int distance = map.GetDistance(anchorUnit.Position, tile);
                    if (distance <= 1)
                    {
                        inRange = true;
                        break;
                    }
                }

                // If no CMP is in range, check proximity to Hub building.
                if (!inRange)
                {
                    foreach (Building anchorBuilding in OwnedBuildings)
                    {
                        if (anchorBuilding == null || anchorBuilding.Position == null)
                            continue;

                        if (anchorBuilding.ThisBuildingType != Building.BuildingType.Hub)
                            continue;

                        int distance = map.GetDistance(anchorBuilding.Position, tile);
                        if (distance <= 1)
                        {
                            inRange = true;
                            break;
                        }
                    }
                }

                if (!inRange)
                    return false;
            }

            // Only spend resources if deployment is truly allowed.
            if (!SpendAlloyResources(unit.PriceAlloy))
                return false;

            // Update player-owned lists.
            AvailableUnitsToPlace.Remove(unit);
            DeployedUnits.Add(unit);


            return true;
        }


        /// <summary>
        /// Adds a unit into the player's AvailableUnitsToPlace list (if not already present).
        /// Used after purchasing or when loading a saved game.
        /// </summary>
        public void AddUnit(Unit unit)
        {
            if (unit != null && !AvailableUnitsToPlace.Contains(unit))
            {
                AvailableUnitsToPlace.Add(unit);
            }
        }
        /// <summary>
        /// Removes a unit from both deployed and available collections.
        /// Used when unit is destroyed or removed from the game.
        /// </summary>
        public void RemoveUnit(Unit unit)
        {
            if (unit == null)
                return;

            DeployedUnits.Remove(unit);
            AvailableUnitsToPlace.Remove(unit);
        }

        /// <summary>
        /// Refreshes per-turn unit state:
        /// - clears action flags so units can act again
        /// - restores range and speed back to original values
        /// 
        /// Intended to be called at the start of a player's turn.
        /// </summary>
        public void RefreshUnits()
        {
            foreach (Unit unit in DeployedUnits)
            {
                if (unit != null)
                {
                    unit.HasPerformedAction = false;
                    unit.RefreshRangeAndSpeed();
                }
            }
        }

        // ============================================================
        // BUILDING MANAGEMENT
        // ============================================================
        /// <summary>
        /// Adds a building into the player's AvailableBuildingsToPlace list (if not already present).
        /// Used after purchasing or when loading a saved game.
        /// </summary>
        public void AddBuilding(Building building)
        {
            if (building != null && !AvailableBuildingsToPlace.Contains(building))
            {
                AvailableBuildingsToPlace.Add(building);
            }
        }
        /// <summary>
        /// Removes a building from the player's ownership and available lists.
        /// Also updates building income afterwards.
        /// </summary>
        public void RemoveBuilding(Building building)
        {
            if (building == null)
                return;

            // If the building is owned, remove from owned list.
            if (OwnedBuildings.Contains(building))
            {
                OwnedBuildings.Remove(building);
            }

            // Remove from placement pool as well.
            AvailableBuildingsToPlace.Remove(building);

            // Income changes when buildings change.
            UpdateBuildingIncome();
        }

        /// <summary>
        /// Places a building on a given tile on the map.
        /// 
        /// Validation:
        /// - building/tile/map must be non-null
        /// - building must be in AvailableBuildingsToPlace
        /// - tile must not already contain a building
        /// 
        /// Then:
        /// - PurchaseUnit(building) spends Alloy cost (but does not return a success/failure)
        /// - map.PlaceBuilding(building, tile) updates map state
        /// - move building from available -> owned
        /// </summary>
        public bool PlaceBuilding(Building building, Tile tile, Map map)
        {
            if (building == null || tile == null || map == null)
                return false;

            if (!AvailableBuildingsToPlace.Contains(building))
                return false;

            if (tile.Building != null)
                return false;

            // Deduct cost (but PurchaseUnit currently does not return failure).
            PurchaseUnit(building);

            // Place into map state.
            map.PlaceBuilding(building, tile);

            // Move from available list to owned list.
            AvailableBuildingsToPlace.Remove(building);
            OwnedBuildings.Add(building);

            UpdateBuildingIncome();

            return true;
        }
        // ============================================================
        // SUMMARY / STATUS HELPERS
        // ============================================================

        /// <summary>
        /// Refills fuel for every deployed unit.
        /// </summary>
public void RefillAllUnitsFuel()
{
    foreach (Unit unit in DeployedUnits)
    {
        if (unit != null)
            unit.RefillFuel();
    }
}
     
    }
}
